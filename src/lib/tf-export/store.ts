// tf-export job and stats store: JSON files, atomic writes on one serialized chain / tf-export 작업·지표 저장소: JSON 파일, 하나의 직렬 체인에서 원자적 쓰기
import fs from 'node:fs';
import path from 'node:path';
import type { JobRecord, JobStats } from './types';

// Records (and job folders) kept / 남기는 기록(과 작업 폴더) 수
export const MAX_JOBS = 20;
const JOBS_FILE = 'jobs.json';
const STATS_FILE = 'stats.json';

// Cumulative stats across jobs / 작업 누적 지표
export interface StatsTotals extends JobStats { jobs: number; updatedAt: string | null }

// Process-wide state (Next.js may load modules twice) / 프로세스 전역 상태 (Next.js가 모듈을 두 번 올릴 수 있음)
export interface TfExportState {
  writes: Promise<unknown>;
  running: string | null;
  jobs: Map<string, JobRecord>;
  recovered: boolean;
}
declare global {
  // eslint-disable-next-line no-var
  var __awsopsTfExport: TfExportState | undefined;
}
export function tfExportState(): TfExportState {
  return (globalThis.__awsopsTfExport ??= { writes: Promise.resolve(), running: null, jobs: new Map(), recovered: false });
}

// data/tf-export under cwd; TF_EXPORT_DATA_DIR overrides it (tests) / 기본 data/tf-export, 테스트는 TF_EXPORT_DATA_DIR로 재정의
export function tfExportDir(): string {
  return process.env.TF_EXPORT_DATA_DIR || path.join(process.cwd(), 'data', 'tf-export');
}
export function jobsRoot(): string {
  return path.join(tfExportDir(), 'jobs');
}
// Job ids are generated by us; anything else is rejected / 작업 id는 우리가 만든 형식만 허용
export const JOB_ID = /^\d{8}-\d{6}-[0-9a-f]{6}$/;
export function jobDir(id: string): string {
  if (!JOB_ID.test(id)) throw new Error('BadJobId');
  return path.join(jobsRoot(), id);
}

// Missing → fallback; unparseable → moved aside, fallback; other I/O errors thrown / 없으면 기본값, 깨졌으면 옆으로 옮기고 기본값, 그 외 오류는 throw
async function readJson<T>(file: string, ok: (v: unknown) => boolean, fallback: T): Promise<T> {
  let text: string;
  try {
    text = await fs.promises.readFile(file, 'utf8');
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') return fallback;
    throw e;
  }
  try {
    const v = JSON.parse(text);
    if (ok(v)) return v as T;
    throw new SyntaxError('shape');
  } catch {
    console.error('[tf-export] CorruptStoreFile');
    await fs.promises.rename(file, `${file}.corrupt-${Date.now()}`).catch(() => undefined);
    return fallback;
  }
}

// tmp + rename / 임시 파일 + rename
async function writeJson(file: string, value: unknown): Promise<void> {
  await fs.promises.mkdir(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.${Date.now()}.tmp`;
  try {
    await fs.promises.writeFile(tmp, JSON.stringify(value, null, 2));
    await fs.promises.rename(tmp, file);
  } catch (e) {
    await fs.promises.rm(tmp, { force: true }).catch(() => undefined);
    throw e;
  }
}

// Run on the shared write chain / 공용 쓰기 체인에서 실행
function serial<T>(fn: () => Promise<T>): Promise<T> {
  const s = tfExportState();
  const p = s.writes.then(fn);
  s.writes = p.catch(() => undefined);
  return p;
}

export function readJobs(): Promise<JobRecord[]> {
  return readJson<JobRecord[]>(path.join(tfExportDir(), JOBS_FILE), Array.isArray, []);
}

// Upsert a job, newest first, keep 20 and delete other job folders / 작업 저장(최신순), 20개만 남기고 나머지 폴더 삭제
export function saveJob(job: JobRecord): Promise<void> {
  const snapshot = JSON.parse(JSON.stringify(job)) as JobRecord;
  return serial(async () => {
    const list = (await readJobs()).filter(j => j.id !== snapshot.id);
    list.push(snapshot);
    list.sort((a, b) => (a.startedAt < b.startedAt ? 1 : a.startedAt > b.startedAt ? -1 : a.id < b.id ? 1 : -1));
    const kept = list.slice(0, MAX_JOBS);
    await writeJson(path.join(tfExportDir(), JOBS_FILE), kept);
    const keep = new Set(kept.map(j => j.id));
    let names: string[] = [];
    try { names = await fs.promises.readdir(jobsRoot()); } catch { /* no folder yet / 아직 폴더 없음 */ }
    for (const n of names) if (JOB_ID.test(n) && !keep.has(n)) await fs.promises.rm(path.join(jobsRoot(), n), { recursive: true, force: true });
  });
}

// Zeroed totals / 0으로 채운 누적값
export function emptyTotals(): StatsTotals {
  return { jobs: 0, total: 0, passRules: 0, passAi: 0, passFinal: 0, pure: 0, ignore: 0, failed: 0, byType: {}, aiCalls: 0, inputTokens: 0, outputTokens: 0, updatedAt: null };
}

export async function readStats(): Promise<StatsTotals> {
  const v = await readJson<StatsTotals>(path.join(tfExportDir(), STATS_FILE), x => !!x && typeof x === 'object' && !Array.isArray(x), emptyTotals());
  return { ...emptyTotals(), ...v };
}

// Add one job's stats to the totals / 작업 하나의 지표를 누적값에 더하기
export function addStats(s: JobStats): Promise<StatsTotals> {
  return serial(async () => {
    const t = await readStats();
    const keys = ['total', 'passRules', 'passAi', 'passFinal', 'pure', 'ignore', 'failed', 'aiCalls', 'inputTokens', 'outputTokens'] as const;
    for (const k of keys) t[k] += s[k];
    for (const [type, v] of Object.entries(s.byType) as Array<[keyof JobStats['byType'], { total: number; pass: number }]>) {
      const cur = t.byType[type] ?? { total: 0, pass: 0 };
      t.byType[type] = { total: cur.total + v.total, pass: cur.pass + v.pass };
    }
    t.jobs += 1;
    t.updatedAt = new Date().toISOString();
    await writeJson(path.join(tfExportDir(), STATS_FILE), t);
    return t;
  });
}
